// File-system helpers shared by the site's scripts.
//
// All generated content carries `GENERATED_MARKER`, so writers can refuse to
// overwrite hand-written files and pruning can delete only files this pipeline
// owns. Writers also skip files whose contents are unchanged, which keeps
// `mtime` stable and avoids pointless reloads and dirty git trees.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const GENERATED_MARKER = '<!-- @generated by scripts/sync-content.mjs; do not edit -->';

/** Reads and parses a JSON file. */
export function readJsonFile(path) {
    return JSON.parse(readFileSync(path, 'utf8'));
}

/**
 * Writes `contents` to `path`, creating parent directories as needed.
 * Returns `'created'`, `'updated'`, or `'unchanged'` (contents identical, file
 * left untouched).
 */
export function writeFileIfChanged(path, contents) {
    let previous;

    try {
        previous = readFileSync(path, 'utf8');
    } catch {
        previous = undefined;
    }

    if (previous === contents) {
        return 'unchanged';
    }

    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);

    return previous === undefined ? 'created' : 'updated';
}

/**
 * Deletes files in `directory` that carry `GENERATED_MARKER` and are not in
 * `keepNames` (basenames). Hand-written files are never touched. Returns the
 * sorted list of deleted basenames. Missing directories prune to nothing.
 */
export function pruneOwnedFiles(directory, keepNames, marker = GENERATED_MARKER) {
    let entries;

    try {
        entries = readdirSync(directory);
    } catch {
        return [];
    }

    const deleted = [];

    for (const entry of entries.sort()) {
        if (keepNames.has(entry)) {
            continue;
        }

        let contents;

        try {
            contents = readFileSync(join(directory, entry), 'utf8');
        } catch {
            continue;
        }

        if (contents.includes(marker)) {
            rmSync(join(directory, entry));
            deleted.push(entry);
        }
    }

    return deleted;
}
